/* справка на тройку: o.n — ФИО, o.b — год и место рождения, o.soc, o.now, o.kom, o.src — строки справки;
   o.app = [заголовок, подзаголовок, [строки]] — приложение; o.pairs = [[a, b]] — что с чем сверяется; o.t — что это даёт */
function K(id, o) {
  const k = { id, pr: o.pr || 1, cost: o.cost || 40, tag: o.tag, kin: o.kin, if: o.if, dop: o.dop, note: o.note, retCost: o.retCost,
    fate1: o.fate1, fate2: o.fate2,
    person: { name: o.n, face: Object.assign({ s: o.f ? 'f' : 'm', age: o.age, seed: o.seed, gaunt: 1 }, o.face || {}) },
    lines: [
      L('fio', 'Фамилия, имя, отчество', o.n),
      L('born', 'Год и место рождения', o.b),
      L('soc', 'Социальное прошлое', o.soc),
      L('now', 'Занятие до ареста', o.now),
      L('kom', 'Компрометирующие материалы', o.kom),
      L('src', 'Основание', o.src) ],
    app: o.app ? { title: o.app[0], sub: o.app[1], req: o.app[3], lines: o.app[2].map((v, i) => L('a' + (i + 1), null, v)) } : null,
    pairs: (o.pairs || []).map(p => ({ a: p[0], b: p[1], f: 'f' })),
    findings: o.t ? { f: { kind: o.kind || 'ex', w: o.w, t: o.t } } : {} };
  ALBCARDS[id] = k;
  return k;
}

