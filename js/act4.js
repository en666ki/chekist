/* жалоба по полному делу: на столе — старое дело как есть */
function RV(old, o) {
  const oc = CASES[old], ks = k => Object.keys(oc.findings).filter(f => oc.findings[f].kind === k);
  CASES['rv_' + old] = { review: old, no: oc.no, title: 'Жалоба', charge: o.charge, if: o.if, prio: o.prio, person: oc.person, note: o.note,
    docs: oc.docs.concat(o.docs), requests: oc.requests || [], pairs: oc.pairs.concat(o.pairs || []), findings: Object.assign({}, oc.findings, o.findings || {}),
    verdicts: V4(old, o.who, ks('ex'), ks('in'), Object.assign({ kneed: Math.max(1, Math.min(2, ks('in').reduce((a, f) => a + (oc.findings[f].w || 2), 0))) }, o)) };
  return 'rv_' + old;
}
